"""
Advantages of using an IDE debugger over print statements.
"""

def explain_debugger_advantages():
    """
    Print the benefits of using an IDE debugger
    """
    print("1. Goes through the code one line at a time.")
    print("2. Inspect variable values without modifying the program.")
    print("3. Set breakpoints to pause execution at specified locations.")
    print("4. View the call stack to understand function execution.")
    print("5. Debug complex programs more efficiently than using print statements.")


if __name__ == "__main__":
    explain_debugger_advantages()